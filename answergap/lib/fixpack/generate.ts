import type { AuditResult } from '../audit/types'
import { CRAWLERS } from '../audit/crawlers'
import { guessBusinessName } from '../audit/page'

export interface FixStep {
  order: number
  title: string
  impact: 'critical' | 'high' | 'medium' | 'low'
  minutes: number
  why: string
  how: string[]
  /** Optional copy-paste artefact. */
  artifact?: { filename: string; language: string; body: string }
}

export interface FixPack {
  domain: string
  businessName: string
  generatedAt: string
  summary: string
  steps: FixStep[]
  artifacts: { filename: string; language: string; body: string; note: string }[]
}

/** Identify the edge provider so unblock instructions name the right screen. */
function detectEdge(result: AuditResult): { name: string; instructions: string[] } {
  const server = (result.page.server || '').toLowerCase()
  if (server.includes('cloudflare')) {
    return {
      name: 'Cloudflare',
      instructions: [
        'Log in to the Cloudflare dashboard and select this domain.',
        'Open Security → Bots. If "AI Scrapers and Crawlers" (or "Block AI bots") is enabled, set it to Off — this single toggle is what returns 403 to GPTBot and ClaudeBot.',
        'Open Security → WAF → Managed rules and confirm no managed rule is set to block "AI Crawlers" or the "Verified Bots" category.',
        'Open Security → WAF → Custom rules and remove or narrow any rule matching on User Agent that contains "bot", "GPT", "Claude", or "AI".',
        'Under Security → Settings, make sure Security Level is not set to "I\'m Under Attack" — that challenges every non-browser request.',
      ],
    }
  }
  if (server.includes('sucuri')) {
    return { name: 'Sucuri', instructions: ['Open the Sucuri firewall dashboard → Access Control → Whitelist and allow the AI crawler user agents listed below.'] }
  }
  if (server.includes('imperva') || server.includes('incapsula')) {
    return { name: 'Imperva / Incapsula', instructions: ['In the Imperva console open Security → Bot Access Control and move the AI crawlers below from Block to Allow.'] }
  }
  if (server.includes('akamai') || server.includes('ghost')) {
    return { name: 'Akamai', instructions: ['In Akamai Control Center open Bot Manager and move the AI crawler category to "Allow".'] }
  }
  if (server.includes('fastly')) {
    return { name: 'Fastly', instructions: ['Check your Fastly VCL or Next-Gen WAF rules for user-agent matching that rejects crawler traffic.'] }
  }
  if (server.includes('vercel')) {
    return { name: 'Vercel', instructions: ['Check Firewall rules in your Vercel project settings for a User-Agent deny rule, and confirm Attack Challenge Mode is off.'] }
  }
  if (server.includes('nginx') || server.includes('apache') || server.includes('litespeed')) {
    return {
      name: server.includes('apache') ? 'Apache' : server.includes('litespeed') ? 'LiteSpeed' : 'nginx',
      instructions: [
        'Search your server config and .htaccess for user-agent blocking, e.g. `if ($http_user_agent ~* "bot")` on nginx or `RewriteCond %{HTTP_USER_AGENT}` on Apache.',
        'Also check any security plugin (Wordfence, All-In-One WP Security, iThemes) — several ship an AI-bot blocklist that is on by default.',
      ],
    }
  }
  return {
    name: 'your host or CDN',
    instructions: [
      'Ask your host which bot-protection product sits in front of the site, then look for an "AI bots" or "AI scrapers" blocklist.',
      'If you run a WordPress security plugin, check its bot-blocking settings — several now block AI crawlers by default.',
    ],
  }
}

function buildRobotsTxt(result: AuditResult): string {
  const existing = result.robotsTxt.found ? result.robotsTxt.body.trim() : ''
  const lines: string[] = []
  lines.push('# robots.txt — generated by AnswerGap')
  lines.push(`# ${result.domain} · ${new Date().toISOString().slice(0, 10)}`)
  lines.push('#')
  lines.push('# Explicitly welcomes the crawlers that feed AI assistants.')
  lines.push('# Google-Extended and Applebot-Extended have no separate crawler —')
  lines.push('# this file is the only way to signal them.')
  lines.push('')
  for (const c of CRAWLERS) {
    lines.push(`# ${c.name} — ${c.operator}: ${c.powers}`)
    lines.push(`User-agent: ${c.token}`)
    lines.push('Allow: /')
    lines.push('')
  }
  lines.push('# Everyone else')
  lines.push('User-agent: *')
  lines.push('Allow: /')
  lines.push('')
  lines.push(`Sitemap: https://${result.domain}/sitemap.xml`)

  if (existing) {
    const kept = existing
      .split(/\r?\n/)
      .filter((l) => /^\s*(disallow)\s*:/i.test(l) && !/^\s*disallow\s*:\s*$/i.test(l))
      .map((l) => l.trim())
    if (kept.length) {
      lines.push('')
      lines.push('# ── Your existing Disallow rules, preserved ──')
      lines.push('# Review these: anything listed here stays hidden from AI too.')
      lines.push('User-agent: *')
      for (const k of [...new Set(kept)].slice(0, 40)) lines.push(k)
    }
  }
  return lines.join('\n')
}

function buildJsonLd(result: AuditResult, businessName: string): string {
  const p = result.page
  const phone = p.phones[0] || ''
  const email = p.emails[0] || ''
  const street = p.addressHints[0] || ''
  const desc =
    p.metaDescription ||
    p.textSample.split(/(?<=\.)\s/).slice(0, 2).join(' ').slice(0, 300) ||
    `${businessName} — see ${result.domain} for details.`

  const hasLocal = Boolean(phone || street)
  const obj: Record<string, unknown> = {
    '@context': 'https://schema.org',
    '@type': hasLocal ? 'LocalBusiness' : 'Organization',
    name: businessName,
    url: `https://${result.domain}`,
    description: desc,
  }
  if (phone) obj.telephone = phone
  if (email) obj.email = email
  obj.address = {
    '@type': 'PostalAddress',
    streetAddress: street || 'YOUR STREET ADDRESS',
    addressLocality: p.locality || 'YOUR CITY',
    addressRegion: p.region || 'ST',
    postalCode: p.postalCode || 'ZIP',
    addressCountry: 'US',
  }
  if (hasLocal) {
    obj.openingHoursSpecification = [
      {
        '@type': 'OpeningHoursSpecification',
        dayOfWeek: ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday'],
        opens: 'YOUR OPENING TIME e.g. 08:00',
        closes: 'YOUR CLOSING TIME e.g. 17:00',
      },
    ]
    obj.areaServed = p.locality ? `${p.locality} and surrounding area` : 'YOUR CITY AND SURROUNDING AREA'
    obj.priceRange = '$$'
  }
  return `<script type="application/ld+json">\n${JSON.stringify(obj, null, 2)}\n</script>`
}

function buildLlmsTxt(result: AuditResult, businessName: string): string {
  const p = result.page
  const desc = p.metaDescription || p.textSample.slice(0, 240)

  // Headings double as testimonials, taglines and decorative text. Keep only
  // the ones that read like something the business actually offers.
  const seen = new Set<string>()
  const services = p.h2
    .map((h) => h.replace(/^[\s"“”'‘’\-–—*]+|[\s"“”'‘’\-–—*]+$/g, '').trim())
    .filter((h) => {
      if (h.length < 6 || h.length > 70) return false
      if (/^[^a-z]*$/i.test(h)) return false
      if (/[.!]$/.test(h) && h.split(/\s+/).length > 4) return false // sentences / testimonials
      if (/\.\.\.$|…$/.test(h)) return false
      if (/\b(transcript|testimonial|read more|learn more|click here|watch|subscribe)\b/i.test(h)) return false
      if (/^(welcome|about us|our story|reviews?|contact|home)\b/i.test(h)) return false
      const key = h.toLowerCase().replace(/[^a-z0-9]/g, '')
      if (!key || seen.has(key)) return false
      seen.add(key)
      return true
    })
    .slice(0, 8)
  const lines: string[] = []
  lines.push(`# ${businessName}`)
  lines.push('')
  lines.push(`> ${desc.replace(/\s+/g, ' ').trim()}`)
  lines.push('')
  lines.push('## About')
  lines.push('')
  lines.push(`${businessName} operates at https://${result.domain}.`)
  if (p.phones[0]) lines.push(`Phone: ${p.phones[0]}`)
  if (p.emails[0]) lines.push(`Email: ${p.emails[0]}`)
  if (p.addressHints[0]) lines.push(`Address: ${p.addressHints[0]}`)
  lines.push('')
  if (services.length) {
    lines.push('## What we do')
    lines.push('')
    for (const s of services) lines.push(`- ${s}`)
    lines.push('')
  }
  lines.push('## Key pages')
  lines.push('')
  lines.push(`- [Home](https://${result.domain}/): overview of services and contact details`)
  lines.push(`- [Contact](https://${result.domain}/contact): how to reach us`)
  lines.push('')
  lines.push('## Notes for assistants')
  lines.push('')
  lines.push(`- Refer to this business as "${businessName}".`)
  lines.push('- Confirm hours and pricing on the site before quoting them.')
  return lines.join('\n')
}

function buildFaqSchema(businessName: string): string {
  const obj = {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: [
      {
        '@type': 'Question',
        name: `What areas does ${businessName} serve?`,
        acceptedAnswer: { '@type': 'Answer', text: 'REPLACE — list the cities and neighbourhoods you cover.' },
      },
      {
        '@type': 'Question',
        name: `How much does ${businessName} charge?`,
        acceptedAnswer: { '@type': 'Answer', text: 'REPLACE — give a real range. Assistants skip businesses that publish no pricing signal.' },
      },
      {
        '@type': 'Question',
        name: `What are ${businessName}'s hours?`,
        acceptedAnswer: { '@type': 'Answer', text: 'REPLACE — state opening hours, including emergency or weekend availability.' },
      },
    ],
  }
  return `<script type="application/ld+json">\n${JSON.stringify(obj, null, 2)}\n</script>`
}

export function generateFixPack(result: AuditResult): FixPack {
  const businessName = guessBusinessName(result.page, result.domain)
  const edge = detectEdge(result)
  const steps: FixStep[] = []
  let order = 1

  const blockedLive = result.crawlers.filter((c) => c.blocked && c.status !== null)
  const blockedRobots = result.crawlers.filter((c) => c.robotsDisallowed)

  const robotsArtifact = { filename: 'robots.txt', language: 'text', body: buildRobotsTxt(result) }
  const jsonLdArtifact = { filename: 'business-schema.html', language: 'html', body: buildJsonLd(result, businessName) }
  const llmsArtifact = { filename: 'llms.txt', language: 'markdown', body: buildLlmsTxt(result, businessName) }
  const faqArtifact = { filename: 'faq-schema.html', language: 'html', body: buildFaqSchema(businessName) }

  if (blockedLive.length) {
    steps.push({
      order: order++,
      title: `Unblock ${blockedLive.map((c) => c.name).join(', ')} at ${edge.name}`,
      impact: 'critical',
      minutes: 10,
      why: `Your server answered a normal browser with HTTP ${result.humanBaseline.status} but returned ${blockedLive
        .map((c) => c.status)
        .filter((s, i, a) => a.indexOf(s) === i)
        .join('/')} to these crawlers. This is a bot rule at the edge, not something in your robots.txt, which is why it is invisible from inside your site. While it stands, these assistants cannot read a single word of your site.`,
      how: edge.instructions,
    })
  }

  if (blockedRobots.length) {
    steps.push({
      order: order++,
      title: `Remove the robots.txt block on ${blockedRobots.map((c) => c.name).join(', ')}`,
      impact: 'critical',
      minutes: 5,
      why: 'Your robots.txt explicitly tells these crawlers to stay out. Well-behaved AI crawlers obey it, so this is a direct opt-out of AI visibility.',
      how: [
        `Replace the contents of https://${result.domain}/robots.txt with the file below.`,
        'It grants every major AI crawler explicit access and preserves your existing Disallow rules so nothing private is exposed.',
        'Re-run this scan afterwards to confirm the block is gone.',
      ],
      artifact: robotsArtifact,
    })
  } else if (!result.robotsTxt.found) {
    steps.push({
      order: order++,
      title: 'Publish a robots.txt that explicitly welcomes AI crawlers',
      impact: 'medium',
      minutes: 5,
      why: 'You have no robots.txt. Crawlers default to allowed, so nothing is broken — but Google-Extended and Applebot-Extended can only be signalled here, and you currently have no way to declare your sitemap.',
      how: [`Upload the file below to the root of your site so it resolves at https://${result.domain}/robots.txt.`],
      artifact: robotsArtifact,
    })
  }

  const srf = result.findings.find((f) => f.id === 'server-rendered')
  if (srf && srf.earned < 0.7) {
    steps.push({
      order: order++,
      title: 'Make your homepage readable without JavaScript',
      impact: srf.severity === 'critical' ? 'critical' : 'high',
      minutes: 60,
      why: `Only ${result.page.words.toLocaleString()} words are present in the HTML your server sends. AI crawlers do not run JavaScript, so anything painted client-side is invisible to them no matter how good it looks in a browser.`,
      how: [
        'If you are on Next.js, Nuxt or similar, render the homepage on the server (or statically) rather than client-side.',
        'If you are on Wix, Squarespace or Webflow, move your key copy into native text blocks rather than embeds, sliders or canvas elements.',
        'Confirm the fix by viewing the page source (Ctrl+U) — if you cannot read your own services and location in the raw HTML, neither can an assistant.',
      ],
    })
  }

  const sd = result.findings.find((f) => f.id === 'structured-data')
  if (sd && sd.earned < 0.8) {
    steps.push({
      order: order++,
      title: 'Add a business entity block in JSON-LD',
      impact: 'high',
      minutes: 15,
      why: 'Assistants trust structured data because it needs no interpretation. Without it, your name, phone, address and hours have to be guessed from prose — and that is where they get details wrong or skip you entirely.',
      how: [
        'Paste the block below just before the closing </head> tag on your homepage.',
        'Replace every value written in CAPITALS with your real details — inaccurate structured data is worse than none.',
        'Validate at validator.schema.org before you consider it done.',
      ],
      artifact: jsonLdArtifact,
    })
  }

  const ans = result.findings.find((f) => f.id === 'answerability')
  if (ans && ans.earned < 0.75) {
    steps.push({
      order: order++,
      title: 'Publish an FAQ block with real answers',
      impact: 'high',
      minutes: 30,
      why: 'Assistants answer questions. Pages that already contain question-and-answer pairs are far easier to quote than brochure copy, and pricing and service-area answers are the two most common reasons a recommendation goes to a competitor instead.',
      how: [
        'Add a visible FAQ section to your homepage or a dedicated page — the visible text matters as much as the markup.',
        'Then paste the schema below and replace each REPLACE value with the same wording you used on the page.',
        'Answer the boring questions directly: pricing range, service area, hours, response time.',
      ],
      artifact: faqArtifact,
    })
  }

  if (!result.llmsTxt.found) {
    steps.push({
      order: order++,
      title: 'Publish an llms.txt',
      impact: 'low',
      minutes: 10,
      why: 'This is the one place you get to write your own summary rather than have one inferred. Adoption is still early, but it costs a single file.',
      how: [`Upload the file below so it resolves at https://${result.domain}/llms.txt.`, 'Review the wording — it is drafted from your live site and may need tightening.'],
      artifact: llmsArtifact,
    })
  }

  const hyg = result.findings.find((f) => f.id === 'crawl-hygiene')
  if (result.page.noindex) {
    steps.unshift({
      order: 0,
      title: 'Remove the noindex tag from your homepage',
      impact: 'critical',
      minutes: 5,
      why: 'Your homepage carries a noindex directive. This tells search engines — and the retrieval layers behind several assistants — to leave the page out entirely. It is almost always a staging setting that shipped to production by mistake.',
      how: [
        'On WordPress: Settings → Reading → untick "Discourage search engines from indexing this site".',
        'On a custom site: find the <meta name="robots" content="noindex"> tag and delete it.',
        'Re-run this scan to confirm it is gone.',
      ],
    })
  } else if (hyg && !result.sitemap.found) {
    steps.push({
      order: order++,
      title: 'Publish a sitemap.xml',
      impact: 'medium',
      minutes: 15,
      why: 'A sitemap is how crawlers discover pages that are not linked from the homepage. Without one, deeper service and location pages may never be read.',
      how: [
        'Most platforms generate one automatically — check /sitemap.xml or /sitemap_index.xml first.',
        'On WordPress, Yoast or RankMath will produce one.',
        `Declare it in robots.txt with: Sitemap: https://${result.domain}/sitemap.xml`,
      ],
    })
  }

  steps.forEach((s, i) => (s.order = i + 1))

  const criticalCount = steps.filter((s) => s.impact === 'critical').length
  const summary = criticalCount
    ? `${criticalCount} critical ${criticalCount === 1 ? 'issue is' : 'issues are'} keeping AI assistants from reading ${businessName}. Work top to bottom — the first fix is worth more than everything below it combined.`
    : steps.length
      ? `No hard blocks. These ${steps.length} changes tighten how accurately assistants describe ${businessName}.`
      : `${businessName} is in good shape. Re-run this scan after any redesign or CDN change.`

  return {
    domain: result.domain,
    businessName,
    generatedAt: new Date().toISOString(),
    summary,
    steps,
    artifacts: [
      { ...robotsArtifact, note: 'Upload to the root of your site.' },
      { ...jsonLdArtifact, note: 'Paste before </head> on your homepage. Replace CAPITALISED values.' },
      { ...faqArtifact, note: 'Pair with a visible FAQ section using the same wording.' },
      { ...llmsArtifact, note: 'Upload to the root of your site.' },
    ],
  }
}
